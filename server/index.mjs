import pg from 'pg';
import { readFile } from 'node:fs/promises';
import { MailStore } from './core.mjs';
import { createApi } from './app.mjs';
import { createSmtp } from './smtp.mjs';
const {DATABASE_URL,MAIL_DOMAIN,MAIL_API_KEY}=process.env;
if(!DATABASE_URL || !MAIL_DOMAIN || !/^[a-z0-9.-]+$/.test(MAIL_DOMAIN) || !MAIL_API_KEY || MAIL_API_KEY.length<32) throw new Error('Set DATABASE_URL, MAIL_DOMAIN and MAIL_API_KEY (at least 32 characters).');
const pool=new pg.Pool({connectionString:DATABASE_URL,max:10,connectionTimeoutMillis:5000,options:'-c statement_timeout=5000'});
pool.on('error',()=>console.error(JSON.stringify({event:'database_error'})));
await pool.query(await readFile(new URL('./schema.sql',import.meta.url),'utf8'));
const store=new MailStore(pool,MAIL_DOMAIN);
await store.purge();
const api=createApi(store,MAIL_API_KEY);
const smtp=createSmtp(store,api.log);
smtp.on('error',()=>api.log.error('SMTP listener error'));
await new Promise((resolve,reject)=>{smtp.once('error',reject);smtp.listen(Number(process.env.SMTP_PORT || 2525),'0.0.0.0',resolve);});
await api.listen({port:Number(process.env.PORT || 8080),host:'0.0.0.0'});
let busy=false;
const timer=setInterval(async()=>{if(busy)return;busy=true;try{await store.purge();}catch{api.log.error('Expiry purge failed');}finally{busy=false;}},250);
for(const signal of ['SIGINT','SIGTERM']) process.on(signal,async()=>{clearInterval(timer);smtp.close();await api.close();await pool.end();process.exit(0);});
